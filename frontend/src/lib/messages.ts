export function translate(locale: UiLocale, key: MessageKey, values: Record<string, string | number> = {}): string {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

// Only translate our own known errors. Unknown backend messages remain verbatim.
export function localizeError(message: string, locale: UiLocale): string {
  const key = (Object.keys(RU) as MessageKey[]).find((item) => RU[item] === message);
  return key ? translate(locale, key) : message;
}
